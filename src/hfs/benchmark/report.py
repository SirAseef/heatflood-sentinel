"""Report generator (FR-BM-04): figures (PNG), LaTeX booktabs tables and a Markdown summary.

python -m hfs.benchmark.report   ->  results/figures/*.png, results/latex/*.tex, results/RESULTS.md
"""
from __future__ import annotations

import json

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

from hfs.common import config  # noqa: E402

COL = {"persistence": "#9CA3AF", "diurnal_persistence": "#64748B", "climatology": "#B08968", "sarima": "#EAB308",
       "xgboost": "#16A34A", "lstm": "#2563EB", "convlstm": "#7C3AED"}
plt.rcParams.update({"figure.dpi": 130, "axes.spines.top": False, "axes.spines.right": False, "font.size": 9})


def _t(name):
    p = config.path("results") / "tables" / name
    return pd.read_csv(p) if p.exists() else pd.DataFrame()


def fig_skill(lb, var, unit, fname, xlabel):
    fig, ax = plt.subplots(figsize=(5.2, 3.2))
    for m, g in lb[lb["var"] == var].groupby("model"):
        ax.plot(g["horizon"], g["rmse"], "o-", label=m, color=COL.get(m), lw=2 if m in ("lstm", "convlstm") else 1.3, ms=3.5)
    ax.set_xlabel(xlabel)
    ax.set_ylabel(f"RMSE ({unit})")
    ax.legend(frameon=False, fontsize=7.5)
    ax.grid(alpha=.25)
    fig.tight_layout()
    fig.savefig(config.path("results") / "figures" / fname)
    plt.close(fig)


def to_latex(df: pd.DataFrame, cols: list[str], caption: str, label: str, fname: str, fmt="{:.3f}"):
    lines = ["\\begin{table}[t]", "\\centering", f"\\caption{{{caption}}}", f"\\label{{{label}}}",
             "\\begin{tabular}{" + "l" * 2 + "r" * (len(cols) - 2) + "}", "\\toprule",
             " & ".join(c.replace("_", "\\_") for c in cols) + " \\\\", "\\midrule"]
    for _, r in df[cols].iterrows():
        lines.append(" & ".join(fmt.format(v) if isinstance(v, (float, np.floating)) else str(v).replace("_", "\\_") for v in r) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    out = config.path("results") / "latex"
    out.mkdir(exist_ok=True)
    (out / fname).write_text("\n".join(lines))


def run():
    res = config.path("results")
    (res / "figures").mkdir(exist_ok=True)
    md = ["# Results (auto-generated by `make report`)", "",
          "All numbers come from the run artefacts in `results/`; test split = calendar year 2022 (held out).", ""]
    d, h = _t("leaderboard_daily.csv"), _t("leaderboard_hourly.csv")
    if len(d):
        fig_skill(d, "tmax", "°C", "skill_daily_tmax.png", "lead (days)")
        fig_skill(d, "tp", "mm/day", "skill_daily_tp.png", "lead (days)")
        for var, unit in (("tmax", "°C"), ("tp", "mm")):
            sub = d[(d["var"] == var) & (d["horizon"].isin([1, 3, 7]))].sort_values(["horizon", "rmse"])
            cols = ["horizon", "model", "rmse", "mae", "nse", "ss_vs_persistence", "ss_vs_climatology"]
            to_latex(sub, cols, f"Daily {var} forecasts, test 2022 ({unit}).", f"tab:daily_{var}", f"daily_{var}.tex")
            md += [f"## Daily {var} ({unit}) — leads 1, 3, 7 days", "", sub[cols].round(3).to_markdown(index=False), ""]
    if len(h):
        fig_skill(h, "t2m", "°C", "skill_hourly_t2m.png", "lead (hours)")
        sub = h.sort_values(["var", "horizon", "rmse"])
        cols = ["var", "horizon", "model", "rmse", "mae", "nse", "ss_vs_persistence"]
        to_latex(sub, cols, "Hourly forecasts, test 2022.", "tab:hourly", "hourly.tex")
        md += ["## Hourly T2m (°C) and precipitation (mm/h)", "", sub[cols].round(3).to_markdown(index=False), ""]
    s = _t("significance_daily.csv")
    if len(s):
        cols = ["var", "horizon", "model_a", "model_b", "rmse_diff_a_minus_b", "ci_lo", "ci_hi", "dm_stat", "p_holm", "winner"]
        to_latex(s[cols], cols, "Diebold-Mariano (HLN) and block-bootstrap RMSE differences, Holm-adjusted.", "tab:sig", "significance_daily.tex")
        md += ["## Significance (daily track)", "", s[cols].round(4).to_markdown(index=False), ""]
    det = _t("detection_test.csv")
    if len(det):
        cols = ["hazard", "lead", "model", "positives", "csi", "f1", "pod", "far", "pr_auc", "roc_auc", "brier"]
        cols = [c for c in cols if c in det]
        to_latex(det[cols], cols, "Detection scores, test 2022 (flood labels are reanalysis proxies).", "tab:det", "detection.tex")
        md += ["## Detection (test 2022)", "", det[cols].round(3).to_markdown(index=False), ""]
        full = json.loads((res / "detection_full.json").read_text())
        hw = next(r for r in full["results"] if r["model"] == "xgboost" and r["hazard"] == "heatwave" and r["lead"] == "1d")
        rel = pd.DataFrame(hw["reliability"])
        fig, ax = plt.subplots(figsize=(3.4, 3.2))
        ax.plot([0, 1], [0, 1], "--", color="grey")
        ax.plot(rel["mean_p"], rel["obs_freq"], "o-", color="#EA580C")
        ax.set_xlabel("forecast probability")
        ax.set_ylabel("observed frequency")
        ax.set_title("Heatwave (lead 1 d) reliability")
        fig.tight_layout()
        fig.savefig(res / "figures" / "reliability_heatwave.png")
        plt.close(fig)
    g = _t("grid_convlstm_test.csv")
    if len(g):
        fig, axs = plt.subplots(1, 2, figsize=(7.5, 3))
        for ax, var, unit in zip(axs, ("t2m", "tp"), ("°C", "mm/h")):
            for m, gg in g[g["var"] == var].groupby("model"):
                ax.plot(gg["horizon"], gg["rmse"], "o-", label=m, color=COL.get(m), ms=3)
            ax.set_title(f"ConvLSTM grid — {var}")
            ax.set_xlabel("lead (h)")
            ax.set_ylabel(f"RMSE ({unit})")
            ax.legend(frameon=False, fontsize=7)
        fig.tight_layout()
        fig.savefig(res / "figures" / "convlstm_grid.png")
        plt.close(fig)
        md += ["## ConvLSTM on the 2° ERA5 lattice (test 2022)", "", g.round(4).to_markdown(index=False), ""]
    cp = res / "train_grid_cnn.json"
    if cp.exists():
        c = json.loads(cp.read_text())
        if c.get("train_pos_rate", 0) > 0:
            rp = c.get("rule_persistence", {})
            rows = [{"model": "cnn_grid", **{k: c.get(k) for k in ("csi", "f1", "pod", "far", "pr_auc", "roc_auc", "brier")}},
                    {"model": "rule_persistence", **{k: rp.get(k) for k in ("csi", "f1", "pod", "far")}}]
            md += ["## CNN grid heatwave detector, lead 1 d (test 2022)", "",
                   f"- train positive rate {c['train_pos_rate']:.4f}, test positive rate {c['test_pos_rate']:.4f}, "
                   f"threshold {c['threshold']}, cells×days TP/FP/FN/TN = {c['tp']}/{c['fp']}/{c['fn']}/{c['tn']}", "",
                   pd.DataFrame(rows).round(3).to_markdown(index=False), ""]
        else:
            md += ["## CNN grid heatwave detector", "", "- EXCLUDED: no positive heatwave cells in the training split (train_pos_rate = 0).", ""]
    sp = res / "streaming_local.json"
    if sp.exists():
        st = json.loads(sp.read_text())
        b = st["baseline"]
        md += ["## Streaming (local fallback runtime)", "",
               f"- events: {st['events']}, micro-batches: {b['batches']}, throughput: {b['msgs_per_s']:.0f} msgs/s, {b['gb_per_hour']:.4f} GB/h",
               f"- batch latency p50/p95/p99 (ms): {b['batch_ms']['p50']:.0f} / {b['batch_ms']['p95']:.0f} / {b['batch_ms']['p99']:.0f}",
               f"- event-time→alert end-to-end latency p50/p95/p99 (ms): {b['e2e_ms']['p50']:.0f} / {b['e2e_ms']['p95']:.0f} / {b['e2e_ms']['p99']:.0f}",
               f"- window {st['window'][0]}..{st['window'][1]}; chaos scenarios replay the first {st.get('chaos_window_batches', '–')} batches",
               f"- alerts: {b['alerts']}, DLQ: {b['dlq']}", ""]
        if "chaos" in st:
            md += ["| scenario | DLQ | alerts | duplicate alert events | identical to baseline |", "|---|---|---|---|---|"]
            for k, v in st["chaos"].items():
                md.append(f"| {k} | {v.get('dlq', '–')} | {v.get('alerts', '–')} | {v.get('duplicate_alert_events')} | "
                          f"{v.get('alerts_identical_to_baseline', v.get('alerts_equal_to_uninterrupted'))} |")
            md.append("")
    sc = res / "scalability_local.json"
    if sc.exists():
        s2 = json.loads(sc.read_text())
        fig, axs = plt.subplots(1, 2, figsize=(7, 2.8))
        v = pd.DataFrame(s2["E1_volume"])
        axs[0].plot(v["volume_x"], v["seconds"], "o-")
        axs[0].set_xlabel("data volume (×)")
        axs[0].set_ylabel("runtime (s)")
        axs[0].set_title(f"E1 volume (R²={s2['E1_r2_linear']:.3f})")
        w = pd.DataFrame(s2["E2_workers"])
        axs[1].plot(w["workers"], w["speedup"], "o-", label="speedup")
        axs[1].plot(w["workers"], w["workers"], "--", color="grey", label="ideal")
        axs[1].set_xlabel("worker processes")
        axs[1].set_title("E2 workers")
        axs[1].legend(frameon=False)
        fig.tight_layout()
        fig.savefig(res / "figures" / "scalability.png")
        plt.close(fig)
        md += ["## Scalability (local, 2 vCPU)", "", v.round(3).to_markdown(index=False), "", w.round(3).to_markdown(index=False), ""]
    tc = res / "tables" / "stream_trigger.csv"
    if tc.exists():
        md += ["### E3 trigger interval (stream micro-batch size, May 2022)", "", pd.read_csv(tc).round(1).to_markdown(index=False), ""]
    lv = config.path("gold") / "live" / "live_snapshot.json"
    if lv.exists():
        L = json.loads(lv.read_text())
        md += ["## Live snapshot (Open-Meteo, real time)", "",
               f"- generated (UTC): {L['generated_utc']}; events streamed: {L['events_streamed']}; ERA5 latest: {L.get('era5_latest')}; "
               f"forecast host: {L.get('forecast_host')}", "",
               "| city | current T2m (°C) | RH (%) | P(heatwave) model | forecast hot days > p95 | max 24 h rain fcst (mm) | open alerts |",
               "|---|---|---|---|---|---|---|"]
        for c in L["cities"]:
            hp = c.get("heatwave_prob_model")
            md.append(f"| {c['city']} | {c['current'].get('temperature_2m')} | {c['current'].get('relative_humidity_2m')} | "
                      f"{'–' if hp is None else f'{hp:.2f}'} | {c['forecast_hot_days_above_p95']} | {c['forecast_max_rain_24h_mm']} | {len(c['open_alerts'])} |")
        md.append("")
    # case study figure: Jacobabad 2022 heat (obs + daily forecasts lead 1)
    pdir = config.path("gold") / "preds"
    if (pdir / "daily_lstm.parquet").exists():
        fig, ax = plt.subplots(figsize=(7.5, 3))
        for m in ("persistence", "sarima", "xgboost", "lstm"):
            p = pd.read_parquet(pdir / f"daily_{m}.parquet")
            p = p[(p.entity_id == "Jacobabad") & (p["var"] == "tmax") & (p.horizon == 3) & (p.target_time >= "2022-04-01") & (p.target_time <= "2022-06-30")]
            if m == "persistence":
                ax.plot(p.target_time, p.y, color="black", lw=2, label="observed (ERA5)")
            ax.plot(p.target_time, p.yhat, color=COL[m], lw=1.2, label=f"{m} (+3 d)")
        ax.set_ylabel("daily Tmax (°C)")
        ax.set_title("Jacobabad, pre-monsoon 2022 — 3-day-ahead forecasts")
        ax.legend(frameon=False, fontsize=7, ncol=3)
        fig.tight_layout()
        fig.savefig(res / "figures" / "case_jacobabad_2022.png")
        plt.close(fig)
    (res / "RESULTS.md").write_text("\n".join(md))
    return md


if __name__ == "__main__":
    run()
    print("report written")
